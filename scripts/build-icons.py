#!/usr/bin/env python3
"""Subset the Phosphor icon fonts to the icons the app uses.

The full Phosphor 2.1.1 fonts are 147 KB (regular) and 132 KB (fill) and hold
about 1,500 icons. The app uses about seventy. This keeps those, in both
weights, and writes the CSS that names them.

    python3 scripts/build-icons.py PATH/TO/phosphor-icons-web

PATH is an unpacked @phosphor-icons/web@2.1.1 package (the directory holding
src/regular and src/fill). To get one:

    npm pack @phosphor-icons/web@2.1.1 && tar -xzf phosphor-icons-web-2.1.1.tgz

Reads   src/ui/icons.txt                  the icon names, one per line
Writes  vendor/fonts/phosphor-regular.woff2
        vendor/fonts/phosphor-fill.woff2
        src/ui/icons.css                  @font-face, the .ph and .ph-fill
                                          base rules, one rule per icon

Needs fontTools and brotli: pip install fonttools brotli

The CSS is a fixed function of the list and the package, so running this twice
gives the same file. The fonts are not byte-stable across fontTools versions;
tests/icons.test.js checks the CSS against the list rather than the bytes.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, 'src', 'ui', 'icons.txt')
CSS_OUT = os.path.join(ROOT, 'src', 'ui', 'icons.css')
FONTS = os.path.join(ROOT, 'vendor', 'fonts')


def names():
    out = []
    for line in open(LIST, encoding='utf-8'):
        line = line.strip()
        if line and not line.startswith('#'):
            if not re.match(r'^[a-z0-9-]+$', line):
                sys.exit('icons.txt: not an icon name: %r' % line)
            out.append(line)
    if len(set(out)) != len(out):
        sys.exit('icons.txt lists a name twice')
    return sorted(out)


def codepoints(css_path, prefix):
    """{name: codepoint} from one of Phosphor's style.css files."""
    css = open(css_path, encoding='utf-8').read()
    found = {}
    for m in re.finditer(r'\.' + re.escape(prefix) + r'\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";', css):
        found[m.group(1)] = int(m.group(2), 16)
    if len(found) < 1000:
        sys.exit('%s: found only %d icons; is this Phosphor 2.1.1?' % (css_path, len(found)))
    return found


def subset(src, dest, cps):
    from fontTools import subset as fts
    opts = fts.Options()
    opts.flavor = 'woff2'
    opts.layout_features = []          # no ligatures: the app uses class names
    opts.name_IDs = ['*']              # keep the copyright and licence names
    opts.notdef_outline = True
    font = fts.load_font(src, opts)
    sub = fts.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    fts.save_font(font, dest, opts)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pkg = os.path.join(sys.argv[1], 'src') if os.path.isdir(os.path.join(sys.argv[1], 'src')) else sys.argv[1]
    want = names()
    reg = codepoints(os.path.join(pkg, 'regular', 'style.css'), 'ph')
    fill = codepoints(os.path.join(pkg, 'fill', 'style.css'), 'ph-fill')
    missing = [n for n in want if n not in reg or n not in fill]
    if missing:
        sys.exit('not in Phosphor 2.1.1: ' + ', '.join(missing))
    differ = [n for n in want if reg[n] != fill[n]]
    if differ:
        sys.exit('regular and fill disagree on the codepoint of: ' + ', '.join(differ))

    os.makedirs(FONTS, exist_ok=True)
    cps = sorted(reg[n] for n in want)
    subset(os.path.join(pkg, 'regular', 'Phosphor.woff2'), os.path.join(FONTS, 'phosphor-regular.woff2'), cps)
    subset(os.path.join(pkg, 'fill', 'Phosphor-Fill.woff2'), os.path.join(FONTS, 'phosphor-fill.woff2'), cps)

    lines = [
        '/* GENERATED by scripts/build-icons.py from src/ui/icons.txt. Do not edit.',
        '   Phosphor Icons 2.1.1, MIT licence (vendor/fonts/Phosphor-LICENSE.txt),',
        '   subset to the %d icons the app uses, regular and fill. */' % len(want),
        '@font-face{font-family:"Phosphor";src:url("/vendor/fonts/phosphor-regular.woff2") format("woff2");'
        'font-weight:normal;font-style:normal;font-display:block}',
        '@font-face{font-family:"Phosphor-Fill";src:url("/vendor/fonts/phosphor-fill.woff2") format("woff2");'
        'font-weight:normal;font-style:normal;font-display:block}',
        '.ph,.ph-fill{speak:never;font-style:normal;font-weight:normal;font-variant:normal;text-transform:none;'
        'line-height:1;letter-spacing:0;display:inline-block;-webkit-font-smoothing:antialiased;'
        '-moz-osx-font-smoothing:grayscale}',
        '.ph{font-family:"Phosphor"!important}',
        '.ph-fill{font-family:"Phosphor-Fill"!important}',
    ]
    for n in want:
        lines.append('.ph-%s:before{content:"\\%x"}' % (n, reg[n]))
    open(CSS_OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    for f in ('phosphor-regular.woff2', 'phosphor-fill.woff2'):
        print('%-26s %6d bytes' % (f, os.path.getsize(os.path.join(FONTS, f))))
    print('src/ui/icons.css           %d icons' % len(want))


if __name__ == '__main__':
    main()
